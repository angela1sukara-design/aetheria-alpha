/** 第二轮GPT主写通用词条。每行一个概念，分组示例不作为已经发生的事实。 */
export const expansionGroups=[];
export const expansionSeeds=[];
function group(key,label,library,subcategory,role,facet,subjects,family,usage,example,rows,valueType='nominal'){
  const g={key,label,library,subcategory,role,facet,subjects,family,usage,example,valueType};
  expansionGroups.push(g);
  for(const line of rows.trim().split('\n')){
    const [localKey,name,definition,unit]=line.trim().split('|');
    if(!localKey||!name||!definition)throw Error(`词条缺字段：${line}`);
    expansionSeeds.push({key:`${key}.${localKey}`,group:key,label:name,definition,library,subcategory,role,facet,
      subjects:[...subjects],family,usage,valueType,unit:unit??null});
  }
}

