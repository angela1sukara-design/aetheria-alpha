function coatVisual(coats) {
  const names = coats.map(id => COAT_VISUAL[id]).filter(Boolean);
  if (names.length === 0) return '皮肤上的脏';
  if (names.length === 1) return names[0];
  if (names.length === 2) return `${names[0]}和${names[1]}`;
  return `${names.slice(0, -1).join('、')}和${names[names.length - 1]}`;
}

function remnant(player) {
  if (player.hands === 'gel') return '黑胶手还在灯下自己收紧，手巾从那层皮上滑开。';
  if (player.hands === 'slime') return '透亮的手指还连着细丝，水从指缝里穿过去，形状没有变。';
  if (player.arm === 'vine') return '袖口里的藤还探在外面，水珠顺着纹路往下，没有缩回去。';
  if (player.ears === 'wolf' && player.tail === 'organic') return '狼耳还朝着水声转，长尾在腿后慢慢摆。';
  if (player.ears === 'wolf') return '狼耳还朝着水声转，没有贴回去。';
  if (player.ears === 'antenna') return '触角上的水珠滴干净了，触角还在。';
  if (player.tail === 'organic') return '长尾被水打湿，贴在腿后，没有缩回去。';
  return '';
}

export function washScene(npc, coats, byKeeper, player) {
  const visual = coatVisual(coats);
  const left = remnant(player);
  if (!byKeeper) {
    const done = `你把水浇在皮肤上，搓到${visual}进了地漏。水是浊的。`;
    return left ? `${done}${left}` : done;
  }
  const fn = WASH[npc.trait];
  if (!fn) throw new Error(`缺少擦洗：${npc.trait}`);
  return fn(npc.name, visual, left).trim();
}

export function restoreScene(name, before) {
  const hands = before.hands !== 'human';
  const arm = before.arm === 'vine';
  const ears = before.ears !== 'human';
  const tail = before.tail === 'organic';
  const count = [hands, arm, ears, tail].filter(Boolean).length;
  const wolfOnly = before.ears === 'wolf' && tail && before.hands === 'human' && !arm;
  if (count > 1 && !wolfOnly) {
    return `${name}站在灯影里看着你。那些多出来的轮廓在热水气里一点点收回去，直到你的影子重新贴上墙上原来的形状。这人没有靠近。`;
  }
  if (before.hands === 'gel') return `黑胶从你的手指上退下去，退的时候还在收紧，最后松开。${name}看着那双手变回原来的肤色，水盆里的布没有递过来。`;
  if (before.hands === 'slime') return `细丝断开，透亮从指尖褪掉。${name}看着你把五指分开，又合上。合上时指缝是干的。`;
  if (arm) return `袖口里的藤缩回去，皮肤重新合上。${name}看着那截袖管，直到里面不再动。`;
  if (before.ears === 'antenna') return `触角软下去，缩进头发里。${name}看着你的头顶，灯火不再被那两根东西挡住。`;
  if (before.ears === 'wolf') return `狼耳塌下去，长尾缩回衣摆后面。${name}看着你的影子重新贴住墙，看完才把脚放回地上。`;
  if (tail) return `长尾缩短，最后从衣摆后消失。${name}看着地板上那道不再摆动的影子。`;
  return `${name}看着你。灯下的影子没有再多出一块。`;
}

